#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
Data-pack porter: migrates the Aether mod's data-driven content to a Paper 26.2
datapack.

Migrated: dimension, dimension_type, noise_settings, density_function, noise,
biomes (sanitised), vanilla-compatible recipes/loot/advancements/tags.
Dropped (must be implemented in plugin code): custom feature/structure/placer,
processor, recipe, loot-function/condition/modifier types, custom spawn
categories and custom entity types in spawners.

Outputs:
  build/datapack/            unpacked datapack
  dist/aether-datapack.zip   zipped datapack
  tools/port_data_report.json  what was kept/dropped
"""
import json
import os
import shutil
import zipfile
from collections import OrderedDict

import block_map

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
MODGEN = os.path.join(ROOT, "aether-mod", "src", "generated", "resources", "data")
MODMAIN = os.path.join(ROOT, "aether-mod", "src", "main", "resources", "data")
BUILD = os.path.join(ROOT, "build", "datapack")
DIST = os.path.join(ROOT, "dist")
DATA_PACK_FORMAT = 107
DATA_PACK_MIN = [107, 1]

CUSTOM_PREFIX = "aether:"
report = OrderedDict()


def load(path):
    with open(path, "r", encoding="utf-8", errors="replace") as f:
        return json.load(f)


def dump(path, obj):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", encoding="utf-8") as f:
        json.dump(obj, f, ensure_ascii=False, indent=2)
        f.write("\n")


def parse_carrier(state):
    """'minecraft:note_block[instrument=harp,note=0,powered=false]' -> (id, props dict)"""
    if "[" not in state:
        return state, None
    bid, rest = state.split("[", 1)
    rest = rest.rstrip("]")
    props = {}
    for kv in rest.split(","):
        k, v = kv.split("=", 1)
        props[k] = v
    return bid, props


def replace_blocks(o, bmap, stats):
    if isinstance(o, dict):
        name = o.get("Name")
        if isinstance(name, str) and name.startswith(CUSTOM_PREFIX):
            bid = name.split(":", 1)[1]
            if bid in bmap:
                carrier, props = parse_carrier(bmap[bid])
                o["Name"] = carrier
                if props:
                    o["Properties"] = props
                else:
                    o.pop("Properties", None)
                stats["block_ids_replaced"] += 1
                return o
        for k, v in list(o.items()):
            o[k] = replace_blocks(v, bmap, stats)
        return o
    if isinstance(o, list):
        return [replace_blocks(x, bmap, stats) for x in o]
    return o


def sanitize_biome(b, stats):
    b["features"] = [[] for _ in range(11)]
    b["spawners"] = {
        "monster": [], "creature": [], "ambient": [], "axolotls": [],
        "underground_water_creature": [], "water_ambient": [], "water_creature": [], "misc": [],
    }
    b["spawn_costs"] = {}
    b["carvers"] = []
    if b.get("effects", {}).get("music", {}).get("sound", "").startswith(CUSTOM_PREFIX):
        b["effects"]["music"]["sound"] = "minecraft:music.overworld.forest"
    stats["biomes_sanitised"] += 1
    return b


CUSTOM_FILTERS = {
    "aether:config_filter",
    "aether:improved_layer_placement",
    "aether:dungeon_blacklist_filter",
    "aether:holiday_filter",
}

# Ores and springs cannot be expressed with tags (custom replaceable blocks), so
# they are generated by the plugin chunk populator instead (see tools/ore_populator.json).
ORE_CONFIGURED_DROP = {
    "aether_dirt_ore", "ambrosium_ore", "zanite_ore", "gravitite_ore",
    "gravitite_ore_buried", "icestone_ore", "water_spring",
}

# custom trees re-expressed with vanilla placers (same ids, original heights/blocks)
TREE_SYNTH = {
    "golden_oak_tree": {"trunk": 10, "radius": 3, "height": 4},
    "holiday_tree": {"trunk": 9, "radius": 2, "height": 3},
    "crystal_tree": {"trunk": 7, "radius": 2, "height": 3},
}


def type_values(o, acc):
    if isinstance(o, dict):
        t = o.get("type")
        if isinstance(t, str):
            acc.add(t)
        for v in o.values():
            type_values(v, acc)
    elif isinstance(o, list):
        for v in o:
            type_values(v, acc)
    return acc


def synth_tree(obj, name, stats):
    cfg = obj["config"]
    p = TREE_SYNTH[name]
    cfg["trunk_placer"] = {
        "type": "minecraft:straight_trunk_placer",
        "base_height": p["trunk"],
        "height_rand_a": 0,
        "height_rand_b": 0,
    }
    cfg["foliage_placer"] = {
        "type": "minecraft:blob_foliage_placer",
        "height": p["height"],
        "offset": 0,
        "radius": p["radius"],
    }
    dec = cfg.get("decorators", [])
    if any(isinstance(d, dict) and str(d.get("type", "")).startswith("aether:") for d in dec):
        cfg["decorators"] = []
    stats["trees_synthesised"] += 1
    return patch_tree(obj)


def patch_tree(obj):
    """26.2 renamed the tree dirt provider to below_trunk_provider."""
    cfg = obj.get("config", {})
    if obj.get("type") == "minecraft:tree" and "dirt_provider" in cfg:
        cfg["below_trunk_provider"] = cfg["dirt_provider"]
    return obj


def migrate_patch(obj, stats):
    """random_patch/flower -> simple_block, returning (new_obj, scatter spec)."""
    cfg = obj["config"]
    inner = cfg["feature"]["feature"]
    scatter = {
        "tries": cfg.get("tries", 32),
        "xz": cfg.get("xz_spread", 7),
        "y": cfg.get("y_spread", 3),
    }
    stats["patches_migrated"] += 1
    return {"type": "minecraft:simple_block", "config": inner["config"]}, scatter


def migrate_selector(stem, obj, plc_out, bmap, stats):
    """26.2 random_selector references placed features directly:
    {"default": "<placed-id>", "features": [{"chance": x, "feature": "<placed-id>"}]}.
    Legacy inline entries are wrapped into generated placed features."""
    cfg = obj.get("config", {})

    def convert(entry, suffix):
        # returns the placed-feature id to reference (creating a wrapper if needed)
        if isinstance(entry, str):
            return entry
        if not isinstance(entry, dict):
            return None
        feat = entry.get("feature")
        no_biome = lambda ms: [m for m in ms if not (
            isinstance(m, dict) and m.get("type") == "minecraft:biome")]
        if isinstance(feat, str):
            target = feat
            placement = no_biome(entry.get("placement", []))
        elif isinstance(feat, dict) and isinstance(feat.get("feature"), str):
            target = feat["feature"]
            placement = no_biome(entry.get("placement", []))
        else:
            return None
        name = "aether:" + stem + suffix
        wrapped = replace_blocks({"feature": target, "placement": placement}, bmap, stats)
        plc_out[stem + suffix] = (wrapped, wrapped.get("placement", []), True)
        stats["selectors_migrated"] += 1
        return name

    if "default" in cfg:
        new_default = convert(cfg["default"], "__default")
        if new_default is not None:
            cfg["default"] = new_default
    for idx, f in enumerate(cfg.get("features", [])):
        if isinstance(f, dict) and "feature" in f:
            new_feat = convert(f, "__opt%d" % idx)
            if new_feat is not None:
                f["feature"] = new_feat
    return obj


def scatter_modifiers(scatter):
    xz = scatter["xz"]
    ys = scatter["y"]
    return [
        {"type": "minecraft:count", "count": scatter["tries"]},
        {"type": "minecraft:random_offset",
         "xz_spread": {"type": "minecraft:trapezoid", "max": xz, "min": -xz, "plateau": 0},
         "y_spread": {"type": "minecraft:trapezoid", "max": ys, "min": -ys, "plateau": 0}},
        {"type": "minecraft:block_predicate_filter",
         "predicate": {"type": "minecraft:matching_blocks", "blocks": "minecraft:air"}},
    ]


from minecraft_paths import server_jar
VANILLA_JAR = server_jar()


def vanilla_ids(kind):
    """All vanilla ids of a worldgen registry, read from the reference 26.2 jar."""
    import zipfile
    out = set()
    prefix = "data/minecraft/worldgen/" + kind + "/"
    try:
        with zipfile.ZipFile(VANILLA_JAR) as z:
            for n in z.namelist():
                if n.startswith(prefix) and n.endswith(".json"):
                    out.add("minecraft:" + n[len(prefix):-5])
    except Exception:
        pass
    return out


def feature_refs(obj):
    """Collect all feature-id references (keys named 'feature' with string values)."""
    refs = set()

    def walk(o):
        if isinstance(o, dict):
            f = o.get("feature")
            if isinstance(f, str):
                refs.add(f)
            for v in o.values():
                walk(v)
        elif isinstance(o, list):
            for v in o:
                walk(v)

    walk(obj)
    return refs


def ref_ok(ref, keep_cfg, keep_plc, valid_cfg, valid_plc):
    # "feature"-keyed references point at configured features from placed files
    # and at placed features from inside selector configs; accept either registry.
    if ref.startswith("minecraft:"):
        return ref in valid_cfg or ref in valid_plc
    if not ref.startswith("aether:"):
        return True
    stem = ref.split(":", 1)[1]
    return stem in keep_cfg or stem in keep_plc


def patch_noise_settings(obj, stats):
    """Add fields introduced after 1.21.1 that are required by the 26.2 codec."""
    router = obj.get("noise_router")
    if isinstance(router, dict) and "preliminary_surface_level" not in router:
        final_density = router.get("final_density", 0.0)
        router["preliminary_surface_level"] = {
            "type": "minecraft:find_top_surface",
            "cell_height": 8,
            "density": final_density,
            "lower_bound": 0,
            "upper_bound": 256,
        }
        stats["noise_fields_added"] += 1
    return obj


def main():
    if os.path.isdir(BUILD):
        shutil.rmtree(BUILD)
    os.makedirs(BUILD, exist_ok=True)

    # ---- block map ----
    inv = load(os.path.join(ROOT, "tools", "inventory.json"))
    bmap = block_map.build_map(inv["blocks"])
    stats = {"block_ids_replaced": 0, "biomes_sanitised": 0, "noise_fields_added": 0,
             "trees_synthesised": 0, "placed_synthesised": 0, "patches_migrated": 0,
             "selectors_migrated": 0, "ores_deferred": 0}

    # ---- pack.mcmeta ----
    dump(os.path.join(BUILD, "pack.mcmeta"), {
        "pack": {
            "description": "The Aether - private fan port datapack",
            "max_format": DATA_PACK_FORMAT,
            "min_format": DATA_PACK_MIN,
        }
    })

    aether_out = os.path.join(BUILD, "data", "aether")

    # ---- dimension_type (patched for 26.2) ----
    dt = load(os.path.join(MODGEN, "aether", "dimension_type", "the_aether.json"))
    dt["has_ender_dragon_fight"] = False
    dt["effects"] = "minecraft:overworld"
    dt['skybox']='overworld'
    dt['timelines']='#minecraft:in_overworld'
    dt['attributes']={'minecraft:visual/sky_color':'#b7d9ff',
                      'minecraft:visual/fog_color':'#c0d8ff',
                      # The 26.2 lightmap divides by max(color) during gamma.
                      # Legacy ambient_light=0 becomes black: 0/0 in unlit cells.
                      'minecraft:visual/ambient_light_color':'#181c24',
                      'minecraft:visual/night_vision_color':'#ffffff',
                      # Exact marker read by the scoped sky shader. It is farther
                      # than normal view fog, so ordinary terrain fog still wins.
                      'minecraft:visual/fog_end_distance':8191.25,
                      'minecraft:visual/cloud_color':'#ccffffff',
                      'minecraft:visual/cloud_height':192.33}
    # 26.2 drives time through the world_clock registry; without this the
    # dimension has no clock and World.setTime throws IllegalArgumentException
    dt.setdefault("default_clock", "minecraft:overworld")
    dump(os.path.join(aether_out, "dimension_type", "the_aether.json"), dt)

    # ---- dimension ----
    dim = load(os.path.join(MODGEN, "aether", "dimension", "the_aether.json"))
    dump(os.path.join(aether_out, "dimension", "the_aether.json"), dim)

    # ---- worldgen: noise_settings, density_function, noise (block ids mapped) ----
    kept, dropped = [], []
    # ---- damage types: plain data, no custom references ----
    dtdir = os.path.join(MODGEN, "aether", "damage_type")
    if os.path.isdir(dtdir):
        for fn in sorted(os.listdir(dtdir)):
            if not fn.endswith(".json"):
                continue
            obj = load(os.path.join(dtdir, fn))
            dump(os.path.join(aether_out, "damage_type", fn), obj)
            kept.append(f"damage_type/{fn}")
    wg = os.path.join(MODGEN, "aether", "worldgen")
    for sub in ("noise_settings", "density_function", "noise"):
        src = os.path.join(wg, sub)
        if not os.path.isdir(src):
            continue
        for dirpath, _d, files in os.walk(src):
            for fn in files:
                if not fn.endswith(".json"):
                    continue
                obj = replace_blocks(load(os.path.join(dirpath, fn)), bmap, stats)
                if sub == "noise_settings":
                    obj = patch_noise_settings(obj, stats)
                rel = os.path.relpath(os.path.join(dirpath, fn), wg)
                dump(os.path.join(aether_out, "worldgen", rel), obj)
                kept.append(f"worldgen/{rel}")

    # ---- biomes (sanitised) ----
    bdir = os.path.join(wg, "biome")
    orig_features = {}
    for fn in os.listdir(bdir):
        if not fn.endswith(".json"):
            continue
        b = load(os.path.join(bdir, fn))
        orig_features[fn] = b.get("features", [])
        b = sanitize_biome(b, stats)
        b = replace_blocks(b, bmap, stats)
        dump(os.path.join(aether_out, "worldgen", "biome", fn), b)
        kept.append(f"worldgen/biome/{fn}")

    # ---- configured features: keep vanilla-typed, synthesise custom trees ----
    cfg_out = {}
    plc_out = {}
    scatter_for = {}
    ore_spec = {}
    # surface patches are planted by the plugin populator with strict ground
    # checks (the datapack formers misplace them under islands)
    PATCH_DEFER = {"grass_patch", "tall_grass_patch", "berry_bush_patch",
                   "white_flower_patch", "purple_flower_patch", "water_spring"}
    cdir = os.path.join(wg, "configured_feature")
    if os.path.isdir(cdir):
        for fn in sorted(os.listdir(cdir)):
            if not fn.endswith(".json"):
                continue
            stem = fn[:-5]
            obj = load(os.path.join(cdir, fn))
            if stem in ORE_CONFIGURED_DROP or stem in PATCH_DEFER:
                if stem in ORE_CONFIGURED_DROP:
                    if stem != "water_spring":
                        ore_spec[stem] = obj
                    else:
                        ore_spec["water_spring"] = obj
                    stats["ores_deferred"] += 1
                dropped.append(f"worldgen/configured_feature/{fn}")
                continue
            if obj.get("type") in ("minecraft:random_patch", "minecraft:flower"):
                obj, scatter_for[stem] = migrate_patch(obj, stats)
            types = type_values(obj, set())
            custom = {t for t in types if t.startswith("aether:")}
            if custom and stem not in TREE_SYNTH:
                dropped.append(f"worldgen/configured_feature/{fn}")
                continue
            if stem in TREE_SYNTH:
                obj = synth_tree(obj, stem, stats)
            elif obj.get("type") == "minecraft:tree":
                obj = patch_tree(obj)
            if obj.get("type") == "minecraft:random_selector":
                obj = migrate_selector(stem, obj, plc_out, bmap, stats)
            obj = replace_blocks(obj, bmap, stats)
            cfg_out[stem] = obj

    # ---- placed features: keep vanilla modifiers, drop mod-only filters ----
    pdir = os.path.join(wg, "placed_feature")
    if os.path.isdir(pdir):
        for fn in sorted(os.listdir(pdir)):
            if not fn.endswith(".json"):
                continue
            stem = fn[:-5]
            obj = load(os.path.join(pdir, fn))
            if stem in ORE_CONFIGURED_DROP or stem in PATCH_DEFER:
                if stem in ORE_CONFIGURED_DROP:
                    ore_spec.setdefault(stem, {})["placement"] = obj.get("placement", [])
                    stats["ores_deferred"] += 1
                dropped.append(f"worldgen/placed_feature/{fn}")
                continue
            placement = [m for m in obj.get("placement", [])
                         if not (isinstance(m, dict) and m.get("type") in CUSTOM_FILTERS)]
            if stem in scatter_for:
                placement = placement + scatter_modifiers(scatter_for[stem])
            if not placement and "__" not in stem:
                dropped.append(f"worldgen/placed_feature/{fn}")
                continue
            obj["placement"] = placement
            obj = replace_blocks(obj, bmap, stats)
            plc_out[stem] = (obj, placement,
                             len(placement) != len(load(os.path.join(pdir, fn)).get("placement", [])))

    # ---- fixpoint: drop features whose references cannot resolve ----
    keep_cfg = set(cfg_out)
    keep_plc = set(plc_out)
    valid_vanilla_cfg = vanilla_ids("configured_feature")
    valid_vanilla_plc = vanilla_ids("placed_feature")
    changed = True
    while changed:
        changed = False
        for stem in list(keep_cfg):
            refs = feature_refs(cfg_out[stem])
            if any(not ref_ok(r, keep_cfg - {stem}, keep_plc, valid_vanilla_cfg,
                              valid_vanilla_plc) for r in refs):
                keep_cfg.discard(stem)
                dropped.append(f"worldgen/configured_feature/{stem}.json")
                changed = True
        for stem in list(keep_plc):
            obj, placement, synth = plc_out[stem]
            types = type_values(obj, set())
            custom_left = {t for t in types if t.startswith("aether:")}
            feat = obj.get("feature", "")
            if isinstance(feat, str):
                custom_left.discard(feat)
            bad = bool(custom_left) or any(
                not ref_ok(r, keep_cfg, keep_plc - {stem}, valid_vanilla_cfg,
                           valid_vanilla_plc) for r in feature_refs(obj))
            if bad:
                keep_plc.discard(stem)
                dropped.append(f"worldgen/placed_feature/{stem}.json")
                changed = True

    for stem in sorted(keep_cfg):
        dump(os.path.join(aether_out, "worldgen", "configured_feature", stem + ".json"), cfg_out[stem])
        kept.append(f"worldgen/configured_feature/{stem}.json")
    for stem in sorted(keep_plc):
        obj, _placement, synth = plc_out[stem]
        dump(os.path.join(aether_out, "worldgen", "placed_feature", stem + ".json"), obj)
        kept.append(f"worldgen/placed_feature/{stem}.json")
        if synth:
            stats["placed_synthesised"] += 1

    # ---- restore biome feature steps with the placed features that survived ----
    for fn, steps in orig_features.items():
        path = os.path.join(aether_out, "worldgen", "biome", fn)
        b = load(path)
        new_steps = []
        for step in steps:
            kept_step = [f for f in step
                         if isinstance(f, str) and f.startswith("aether:")
                         and f.split(":", 1)[1] in keep_plc]
            new_steps.append(kept_step)
        while len(new_steps) < 11:
            new_steps.append([])
        b["features"] = [[ref for ref in step if 'tree' not in ref] for step in new_steps[:11]]
        dump(path, b)

    # ---- vanilla-compatible recipes / loot / advancements / tags ----
    custom_recipe_types = set(inv.get("recipe_types", []))
    custom_loot_fns = set(inv.get("loot_functions", []))
    custom_loot_conds = set(inv.get("loot_conditions", []))
    custom_loot_mods = set(inv.get("loot_modifiers", []))

    def is_custom_type(t):
        if not isinstance(t, str):
            return False
        if not t.startswith(CUSTOM_PREFIX):
            return False
        local = t.split(":", 1)[1]
        return local in (custom_recipe_types | custom_loot_fns | custom_loot_conds | custom_loot_mods)

    def has_custom(o):
        if isinstance(o, dict):
            if is_custom_type(o.get("type")):
                return True
            return any(has_custom(v) for v in o.values())
        if isinstance(o, list):
            return any(has_custom(v) for v in o)
        return False

    # Recipes in 1.21.1 use the old ingredient form ({item:...}) and output custom
    # items, so they cannot be loaded as-is. All recipes are reimplemented by the
    # plugin (crafting listeners + recipe registration); the raw data is preserved
    # in aether-mod for reference.
    for sub in ("loot_table", "advancement"):
        src = os.path.join(MODGEN, "aether", sub)
        if not os.path.isdir(src):
            continue
        for fn in sorted(os.listdir(src)):
            if not fn.endswith(".json"):
                continue
            text = open(os.path.join(src, fn), "r", encoding="utf-8", errors="replace").read()
            obj = json.loads(text)
            # references to custom items/blocks/entities cannot resolve in vanilla packs
            if has_custom(obj) or ('"aether:' in text):
                dropped.append(f"{sub}/{fn}")
                continue
            dump(os.path.join(aether_out, sub, fn), obj)
            kept.append(f"{sub}/{fn}")
    recipe_dir = os.path.join(MODGEN, "aether", "recipe")
    if os.path.isdir(recipe_dir):
        for fn in sorted(os.listdir(recipe_dir)):
            if fn.endswith(".json"):
                dropped.append("recipe/" + fn)

    # ---- tags ----
    # The mod's tags reference custom blocks/items/entities and third-party tag
    # namespaces (#c:, #forge:), which vanilla cannot resolve. They are rebuilt by
    # the plugin at runtime instead.
    for srcbase in (MODGEN, MODMAIN):
        tsrc = os.path.join(srcbase, "aether", "tags")
        if not os.path.isdir(tsrc):
            continue
        for dirpath, _d, files in os.walk(tsrc):
            for fn in files:
                dropped.append("tags/" + fn)

    # ---- zip ----
    os.makedirs(DIST, exist_ok=True)
    zpath = os.path.join(DIST, "aether-datapack.zip")
    with zipfile.ZipFile(zpath, "w", zipfile.ZIP_DEFLATED) as z:
        for dirpath, _d, files in os.walk(BUILD):
            for fn in files:
                full = os.path.join(dirpath, fn)
                z.write(full, os.path.relpath(full, BUILD))
    shutil.copy2(zpath, os.path.join(ROOT, 'plugin', 'src', 'main', 'resources',
                                    'aether-datapack.zip'))

    report["kept"] = len(kept)
    report["dropped"] = len(dropped)
    report["dropped_list"] = dropped
    report["stats"] = stats
    report["zip"] = os.path.relpath(zpath, ROOT)
    with open(os.path.join(ROOT, "tools", "ore_populator.json"), "w", encoding="utf-8") as f:
        json.dump(ore_spec, f, ensure_ascii=False, indent=1)
    with open(os.path.join(ROOT, "tools", "port_data_report.json"), "w", encoding="utf-8") as f:
        json.dump(report, f, ensure_ascii=False, indent=1)

    print(f"kept={len(kept)} dropped(custom types)={len(dropped)} blocks_replaced={stats['block_ids_replaced']}")
    print("zip:", os.path.relpath(zpath, ROOT))


if __name__ == "__main__":
    main()
